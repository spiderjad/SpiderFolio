// Generates src/styles/code-theme.css: one rule per color of the github-light (cl-…) and github-dark
// (cd-…) Shiki themes, for the classes that src/lib/shiki-classes.ts puts on code tokens. Run it
// again only when the themes change (node scripts/code-theme.ts); check-dist.ts fails the build if a
// color class has no rule here.
import { writeFileSync } from "node:fs";

interface Theme {
  colors?: Record<string, string>;
  tokenColors?: { settings?: { foreground?: string } }[];
}

async function colorsOf(name: string): Promise<string[]> {
  const theme = ((await import(`@shikijs/themes/${name}`)) as { default: Theme }).default;
  const all = [
    theme.colors?.["editor.foreground"],
    ...(theme.tokenColors ?? []).map((rule) => rule.settings?.foreground),
  ];
  return [
    ...new Set(
      all.flatMap((color) =>
        color !== undefined && /^#[0-9a-f]{3,8}$/i.test(color) ? [color.slice(1).toLowerCase()] : [],
      ),
    ),
  ].sort();
}

const light = await colorsOf("github-light");
const dark = await colorsOf("github-dark");
const css = [
  "/* Generated by scripts/code-theme.ts from the github-light and github-dark Shiki themes. */",
  "/* Light colors apply by default; the dark ones win under .dark (higher specificity). */",
  ...light.map((hex) => `.astro-code .cl-${hex} { color: #${hex}; }`),
  ...dark.map((hex) => `.dark .astro-code .cd-${hex} { color: #${hex}; }`),
  ".astro-code .cl-italic { font-style: italic; }",
  ".astro-code .cl-bold { font-weight: 700; }",
  ".astro-code .cl-underline { text-decoration: underline; }",
  ".dark .astro-code .cl-italic { font-style: normal; }",
  ".dark .astro-code .cl-bold { font-weight: inherit; }",
  ".dark .astro-code .cl-underline { text-decoration: none; }",
  ".dark .astro-code .cd-italic { font-style: italic; }",
  ".dark .astro-code .cd-bold { font-weight: 700; }",
  ".dark .astro-code .cd-underline { text-decoration: underline; }",
  "",
].join("\n");
writeFileSync(new URL("../src/styles/code-theme.css", import.meta.url), css);
console.log(`code-theme.css: ${String(light.length)} light and ${String(dark.length)} dark colors`);
