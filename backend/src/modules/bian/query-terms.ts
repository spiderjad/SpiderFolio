// Palabras de una pregunta para la búsqueda tolerante a faltas de Bian (funciones puras). Se comparan,
// ya sin acentos y en minúsculas, con el texto normalizado de los fragmentos por trigramas (pg_trgm):
// «alerjenos» encuentra «alérgenos». Las palabras vacías («que», «hay», «para»…) no cuentan: por
// parecerse a casi todo, traerían fragmentos de cualquier cosa.

/** Sin acentos ni diéresis y en minúsculas (igual que la columna `textNorm` de la base). */
export function normalizeText(value: string): string {
  return value.normalize("NFD").replace(/\p{M}/gu, "").toLowerCase();
}

