const MAX_WORDS = 8;
/** Largo mínimo: una palabra de tres letras se parece a demasiadas. */
const MIN_LENGTH = 4;

/** Las palabras significativas de la pregunta, para comparar por trigramas. */
export function fuzzyWords(question: string): string[] {
  const words = normalizeText(question)
    .split(/[^a-z0-9]+/u)
    .filter((word) => word.length >= MIN_LENGTH && !STOPWORDS.has(word));
  return [...new Set(words)].slice(0, MAX_WORDS);
}
